import { copyrightHeader } from './copyright-header.mjs'
import Ajv from 'ajv'
import Ajv2020 from 'ajv/dist/2020.js'
import standalone from 'ajv/dist/standalone/index.js'
import { mkdir, writeFile } from 'node:fs/promises'

// Compile only the two bundled, trusted metaschemas at development time.
// Renderer validation never needs eval/new Function or compiles imported schemas.
const target = new URL('../src/validation/generated/', import.meta.url)
await mkdir(target, { recursive: true })
for (const [name, Constructor, id] of [
  ['draft07', Ajv, 'http://json-schema.org/draft-07/schema'],
  ['draft2020', Ajv2020, 'https://json-schema.org/draft/2020-12/schema'],
]) {
  const ajv = new Constructor({ strict: false, allErrors: true, validateFormats: false, code: { source: true, esm: true } })
  const validator = ajv.getSchema(id)
  if (!validator) throw new Error(`Missing metaschema: ${id}`)
  let source = standalone(ajv, validator)
  const imports = []
  source = source.replace(/require\("(ajv\/dist\/runtime\/[^"]+)"\)\.default/g, (_match, path) => {
    const name = `runtime${imports.length}`
    imports.push(`import ${name} from '${path}.js';`)
    return name
  })
  if (source.includes('require(')) throw new Error('Unrecognized runtime dependency in standalone schema')
  await writeFile(new URL(`${name}.js`, target), `${copyrightHeader('.js')}// Generated by scripts/generate-metaschemas.mjs. Do not edit.\n${imports.join('\n')}\n${source}\n`)
  await writeFile(new URL(`${name}.d.ts`, target), copyrightHeader('.ts') + "import type { ValidateFunction } from 'ajv'\ndeclare const validate: ValidateFunction\nexport default validate\n")
}
